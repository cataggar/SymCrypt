pub fn SYMCRYPT_SI_CREATE_ID(comptime si_type: u8, comptime index: u6) UINT64 {
    return (@as(UINT64, si_type) << 56) + (@as(UINT64, 1) << index);
}

pub const SYMCRYPT_SI_INTBITS: u6 = (64 - 8) / 2;
pub const SYMCRYPT_SI_INTMASK: UINT64 = (@as(UINT64, 1) << SYMCRYPT_SI_INTBITS) - 1;

pub fn SYMCRYPT_SI_INTPACK(high: UINT64, low: UINT64) UINT64 {
    return ((high & SYMCRYPT_SI_INTMASK) << SYMCRYPT_SI_INTBITS) | (low & SYMCRYPT_SI_INTMASK);
}

pub fn SYMCRYPT_SI_INTUNPACKLO(x: UINT64) UINT64 {
    return x & SYMCRYPT_SI_INTMASK;
}

pub fn SYMCRYPT_SI_INTUNPACKHI(x: UINT64) UINT64 {
    return (x >> SYMCRYPT_SI_INTBITS) & SYMCRYPT_SI_INTMASK;
}

pub fn SYMCRYPT_SI_INTRANGE(low: UINT64, high: UINT64) UINT64 {
    return (@as(UINT64, SYMCRYPT_SI_TYPE_INTRANGE) << 56) | SYMCRYPT_SI_INTPACK(high, low);
}

pub fn SYMCRYPT_SI_INTPAIR(x: UINT64, y: UINT64) UINT64 {
    return (@as(UINT64, SYMCRYPT_SI_TYPE_INTPAIR) << 56) | SYMCRYPT_SI_INTPACK(y, x);
}

pub fn SYMCRYPT_SI_SIZERANGE(low: UINT64, high: UINT64) UINT64 {
    return (@as(UINT64, SYMCRYPT_SI_TYPE_SIZERANGE) << 56) | SYMCRYPT_SI_INTPACK(high, low);
}

pub fn SYMCRYPT_SI_KEYBITS(l: UINT64) UINT64 {
    return SYMCRYPT_SI_SIZERANGE(l, l);
}

pub fn SYMCRYPT_SI_MODULUS(l: UINT64) UINT64 {
    return SYMCRYPT_SI_SIZERANGE(l, l);
}

pub fn SYMCRYPT_SI_DSAPARAMS(n: UINT64, l: UINT64) UINT64 {
    return SYMCRYPT_SI_INTPAIR(n, l);
}

pub fn SYMCRYPT_SI_SIZE_GTE(x: UINT64) UINT64 {
    return SYMCRYPT_SI_SIZERANGE(x, SYMCRYPT_SI_INTMASK);
}

inline fn SYMCRYPT_SI_HAS_WEIGHT_ONE(x: anytype) bool {
    return (x != 0) and ((x & (x - 1)) == 0);
}

inline fn SYMCRYPT_SI_TYPE_BITS(x: UINT64) BYTE {
    return @truncate(x >> 56);
}

inline fn SYMCRYPT_SI_DATA_BITS(x: UINT64) UINT64 {
    return x & ((@as(UINT64, 1) << 56) - 1);
}

inline fn SYMCRYPT_SI_IS_TYPE_ALG(x: UINT64) bool {
    const t = SYMCRYPT_SI_TYPE_BITS(x);
    return (t > 0x00) and (t < 0x40);
}

inline fn SYMCRYPT_SI_IS_TYPE_BITMASK(x: UINT64) bool {
    const t = SYMCRYPT_SI_TYPE_BITS(x);
    return (t > 0x00) and (t < 0x80);
}

