fn ServiceIndicatorValidateAlgorithm(Alg: UINT64) bool {
    const dataAlg = SYMCRYPT_SI_DATA_BITS(Alg);
    return SYMCRYPT_SI_IS_TYPE_ALG(Alg) and SYMCRYPT_SI_HAS_WEIGHT_ONE(dataAlg);
}

fn ServiceIndicatorValidateParameter(Param: UINT64, Type: u8) bool {
    const typeParam = SYMCRYPT_SI_TYPE_BITS(Param);
    const dataParam = SYMCRYPT_SI_DATA_BITS(Param);
    return (typeParam == Type) and SYMCRYPT_SI_HAS_WEIGHT_ONE(dataParam);
}

fn ServiceIndicatorIsAlgorithmContained(Input: UINT64, Rule: UINT64) bool {
    const typeInput = SYMCRYPT_SI_TYPE_BITS(Input);
    const typeRule = SYMCRYPT_SI_TYPE_BITS(Rule);

    const dataInput = SYMCRYPT_SI_DATA_BITS(Input);
    const dataRule = SYMCRYPT_SI_DATA_BITS(Rule);

    std.debug.assert(SYMCRYPT_SI_IS_TYPE_ALG(Rule));
    std.debug.assert(dataRule != 0);

    return ServiceIndicatorValidateAlgorithm(Input) and
        (typeInput == typeRule) and
        ((dataInput & dataRule) == dataInput);
}

fn ServiceIndicatorIsParameterContained(Input: UINT64, Rule: UINT64) bool {
    const typeRule = SYMCRYPT_SI_TYPE_BITS(Rule);
    const dataInput = SYMCRYPT_SI_DATA_BITS(Input);
    const dataRule = SYMCRYPT_SI_DATA_BITS(Rule);

    std.debug.assert(typeRule != 0);
    std.debug.assert(dataRule != 0);

    return ServiceIndicatorValidateParameter(Input, typeRule) and
        ((dataInput & dataRule) == dataInput);
}

fn ServiceIndicatorIsParamApproved(Input: UINT64, Rule: UINT64) bool {
    var result: bool = false;
    const typeRule = SYMCRYPT_SI_TYPE_BITS(Rule);
    const typeInput = SYMCRYPT_SI_TYPE_BITS(Input);

    if (SYMCRYPT_SI_IS_TYPE_BITMASK(Rule)) {
        // Types must match for bitmask parameters
        if (typeInput != typeRule) {
            return false;
        }

        // We expect the input to be a single bit set from a bitmask
        // of type specified by the rule.
        result = ServiceIndicatorIsParameterContained(Input, Rule);
    } else if (typeRule == SYMCRYPT_SI_TYPE_SIZERANGE) {
        // If the rule is a size range, the input must also be a SIZERANGE
        // and both low and high values must be multiples of 8.
        if (typeInput != SYMCRYPT_SI_TYPE_SIZERANGE) {
            return false;
        }

        const uInputLow = SYMCRYPT_SI_INTUNPACKLO(Input);
        const uInputHigh = SYMCRYPT_SI_INTUNPACKHI(Input);
        const uRuleLow = SYMCRYPT_SI_INTUNPACKLO(Rule);
        const uRuleHigh = SYMCRYPT_SI_INTUNPACKHI(Rule);

        // Only allow values that are multiples of 8
        if ((uInputLow % 8 != 0) or (uInputHigh % 8 != 0)) {
            return false;
        }

        result = (uInputLow >= uRuleLow) and (uInputHigh <= uRuleHigh);
    } else if (typeRule == SYMCRYPT_SI_TYPE_INTRANGE) {
        // If the rule is an integer range, the input can be either:
        // 1. A typed INTRANGE value (e.g. SYMCRYPT_SI_INTRANGE(1, 3))
        // 2. An integer with no type tag, i.e. type tag being 0.
        const uRuleLow = SYMCRYPT_SI_INTUNPACKLO(Rule);
        const uRuleHigh = SYMCRYPT_SI_INTUNPACKHI(Rule);

        if (typeInput == SYMCRYPT_SI_TYPE_INTRANGE) {
            // Input is a typed INTRANGE, check that the input range is contained in the rule range
            const uInputLow = SYMCRYPT_SI_INTUNPACKLO(Input);
            const uInputHigh = SYMCRYPT_SI_INTUNPACKHI(Input);

            result = (uInputLow >= uRuleLow) and (uInputHigh <= uRuleHigh);
        } else if (typeInput == 0) {
            // Input is an integer, check that it is contained in the rule range
            const uInputVal = SYMCRYPT_SI_DATA_BITS(Input);

            result = (uInputVal >= uRuleLow) and (uInputVal <= uRuleHigh);
        } else {
            // Type mismatch
            return false;
        }
    } else if (typeRule == SYMCRYPT_SI_TYPE_INTPAIR) {
        // INTPAIR is used for an exact match of a pair of integers (e.g. DSA parameters)
        if (typeInput != SYMCRYPT_SI_TYPE_INTPAIR) {
            return false;
        }

        result = (Input == Rule);
    } else {
        // covers the NULL parameter case
        result = (Input == Rule);
    }

    return result;
}

pub export fn SymCryptDeprecatedServiceIndicator(
    Service: UINT32,
    Alg: UINT64,
    Param1: UINT64,
    Param2: UINT64,
    Param3: UINT64,
) callconv(SYMCRYPT_CALL) UINT32 {
    _ = Param3;

    // Only one service must be provided
    if (!SYMCRYPT_SI_HAS_WEIGHT_ONE(Service)) {
        return 1;
    }

    // Algorithm has to be of correct type and the remaining part (data bits)
    // has exactly one bit set
    if (!ServiceIndicatorValidateAlgorithm(Alg)) {
        return 1;
    }

    // Search the service indicator data to find whether the given algorithm with
    // the given parameters if any, appear as part of a service
    for (_ServiceIndicatorData) |entry| {
        // Service mask has to be a subset of the defined service data
        if ((Service & entry.Service) == Service) {
            for (entry.pAlgData) |algData| {
                if (ServiceIndicatorIsAlgorithmContained(Alg, algData.Alg)) {
                    // Found a matching entry for the queried algorithm, validate
                    // the parameters
                    if (ServiceIndicatorIsParamApproved(Param1, algData.Param1) and
                        ServiceIndicatorIsParamApproved(Param2, algData.Param2))
                    {
                        // approved status
                        return 0;
                    }
                }
            }
        }
    }

    // non-approved status
    return 1;
}
