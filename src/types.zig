pub inline fn SYMCRYPT_INTERNAL_SIZEOF_MODULUS_FROM_BITS(bitsize: u32) u32 {
    return SYMCRYPT_FDEF_SIZEOF_MODULUS_FROM_DIGITS(SYMCRYPT_FDEF_DIGITS_FROM_BITS(bitsize));
