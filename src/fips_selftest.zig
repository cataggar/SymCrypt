pub export fn SymCryptMlKemSelftest() callconv(SYMCRYPT_CALL) void {
    var scError: SYMCRYPT_ERROR = .SYMCRYPT_NO_ERROR;
    const cbCiphertext: SIZE_T = rgbMlKemSelfTestCiphertext.len;
    const cbDecapsKeyBlob: SIZE_T = @sizeOf(SYMCRYPT_SELFTEST_MLKEMKEY_DECAPS_512);
    const cbAlloc: SIZE_T = cbCiphertext + cbDecapsKeyBlob;
    var rgbComputedSecret: [rgbMlKemSelfTestAgreedSecret.len]BYTE = undefined;
    var pkMlKemkey: ?PSYMCRYPT_MLKEMKEY = null;

    const pbAlloc = SymCryptCallbackAlloc(cbAlloc);
    SYMCRYPT_FIPS_ASSERT(pbAlloc != null);

    const pbCiphertext: PBYTE = pbAlloc.?;
    const pbDecapsKeyBlob: PBYTE = pbAlloc.? + cbCiphertext;

    pkMlKemkey = SymCryptMlKemkeyAllocate(.SYMCRYPT_MLKEM_PARAMS_MLKEM512);
    SYMCRYPT_FIPS_ASSERT(pkMlKemkey != null);

    // ML-KEM KeyGen KAT
    scError = SymCryptMlKemkeySetValue(
        &rgbMlKemKeyPrivateSeed,
        rgbMlKemKeyPrivateSeed.len,
        .SYMCRYPT_MLKEMKEY_FORMAT_PRIVATE_SEED,
        SYMCRYPT_FLAG_KEY_NO_FIPS,
        pkMlKemkey.?,
    );
    SYMCRYPT_FIPS_ASSERT(scError == .SYMCRYPT_NO_ERROR);

    scError = SymCryptMlKemkeyGetValue(
        pkMlKemkey.?,
        pbDecapsKeyBlob,
        cbDecapsKeyBlob,
        .SYMCRYPT_MLKEMKEY_FORMAT_DECAPSULATION_KEY,
        SYMCRYPT_FLAG_KEY_NO_FIPS,
    );
    SYMCRYPT_FIPS_ASSERT(scError == .SYMCRYPT_NO_ERROR);

    SymCryptInjectError(pbDecapsKeyBlob, cbDecapsKeyBlob);

    SYMCRYPT_FIPS_ASSERT(std.mem.eql(u8, pbDecapsKeyBlob[0..cbDecapsKeyBlob], std.mem.asBytes(&mlKemDecapsKey)));

    // ML-KEM Encaps KAT
    scError = SymCryptMlKemEncapsulateEx(
        pkMlKemkey.?,
        &rgbMlKemSelfTestEncapsRandomness,
        rgbMlKemSelfTestEncapsRandomness.len,
        &rgbComputedSecret,
        rgbComputedSecret.len,
        pbCiphertext,
        cbCiphertext,
    );
    SYMCRYPT_FIPS_ASSERT(scError == .SYMCRYPT_NO_ERROR);

    SymCryptInjectError(&rgbComputedSecret, rgbComputedSecret.len);
    SymCryptInjectError(pbCiphertext, rgbMlKemSelfTestCiphertext.len);

    SYMCRYPT_FIPS_ASSERT(std.mem.eql(u8, &rgbComputedSecret, &rgbMlKemSelfTestAgreedSecret));
    SYMCRYPT_FIPS_ASSERT(std.mem.eql(u8, pbCiphertext[0..rgbMlKemSelfTestCiphertext.len], &rgbMlKemSelfTestCiphertext));

    SymCryptWipe(@ptrCast(&rgbComputedSecret), rgbComputedSecret.len);

    // ML-KEM Successful Decaps KAT
    scError = SymCryptMlKemDecapsulate(
        pkMlKemkey.?,
        pbCiphertext,
        cbCiphertext,
        &rgbComputedSecret,
        rgbComputedSecret.len,
    );
    SYMCRYPT_FIPS_ASSERT(scError == .SYMCRYPT_NO_ERROR);

    SymCryptInjectError(&rgbComputedSecret, rgbComputedSecret.len);

    SYMCRYPT_FIPS_ASSERT(std.mem.eql(u8, &rgbComputedSecret, &rgbMlKemSelfTestAgreedSecret));

    SymCryptWipe(@ptrCast(&rgbComputedSecret), rgbComputedSecret.len);

    // ML-KEM Implicit Rejection Decaps KAT
    pbCiphertext[0] ^= 1;

    scError = SymCryptMlKemDecapsulate(
        pkMlKemkey.?,
        pbCiphertext,
        cbCiphertext,
        &rgbComputedSecret,
        rgbComputedSecret.len,
    );
    SYMCRYPT_FIPS_ASSERT(scError == .SYMCRYPT_NO_ERROR);

    SymCryptInjectError(&rgbComputedSecret, rgbComputedSecret.len);

    SYMCRYPT_FIPS_ASSERT(std.mem.eql(u8, &rgbComputedSecret, &rgbMlKemSelfTestImplicitRejectionSecret));

    SymCryptWipe(@ptrCast(&rgbComputedSecret), rgbComputedSecret.len);

    SymCryptMlKemkeyFree(pkMlKemkey.?);
    SymCryptWipe(@ptrCast(pbAlloc.?), cbAlloc);
    SymCryptCallbackFree(@ptrCast(pbAlloc.?));
}

