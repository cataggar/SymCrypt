pub inline fn SYMCRYPT_FDEF_DIGITS_FROM_BITS(bits: UINT32) UINT32 {
    return (bits / SYMCRYPT_FDEF_DIGIT_BITS) + (((bits & (SYMCRYPT_FDEF_DIGIT_BITS - 1)) + (SYMCRYPT_FDEF_DIGIT_BITS - 1)) / SYMCRYPT_FDEF_DIGIT_BITS);
}

pub inline fn SYMCRYPT_FIPS_ASSERT(cond: bool) void {
    if (!cond) {
        macros.SymCryptFatal(comptime macros.multiCharConstant("fkat"));
    }
}

pub inline fn SYMCRYPT_RUN_SELFTEST_ONCE(
    comptime selftestFn: *const fn () callconv(SYMCRYPT_CALL) void,
    comptime flag: UINT32,
) void {
    if ((g_SymCryptFipsSelftestsPerformed & flag) == 0) {
        selftestFn();
        _ = @atomicRmw(UINT32, &g_SymCryptFipsSelftestsPerformed, .Or, flag, .monotonic);
    }
}

pub inline fn SYMCRYPT_RUN_KEY_GEN_PCT(
    comptime pctFn: anytype,
    key: anytype,
    comptime flag: UINT32,
) void {
    if ((key.fAlgorithmInfo & (flag | SYMCRYPT_FLAG_KEY_NO_FIPS)) == 0) {
        SYMCRYPT_FIPS_ASSERT(pctFn(key) == .SYMCRYPT_NO_ERROR);
        _ = @atomicRmw(UINT32, &key.fAlgorithmInfo, .Or, flag, .monotonic);
    }
}

pub export var g_SymCryptFipsSelftestsPerformed: UINT32 = 0;

pub export fn SymCryptFipsGetSelftestsPerformed() callconv(SYMCRYPT_CALL) UINT32 {
    return g_SymCryptFipsSelftestsPerformed;
}

