        0,
        pKey.?,
    );
    SYMCRYPT_FIPS_ASSERT(scError == .SYMCRYPT_NO_ERROR);

    // Make a copy of the signature so that we can inject errors in it
    const pbSignature = SymCryptCallbackAlloc(cbSignature);
    SYMCRYPT_FIPS_ASSERT(pbSignature != null);
    @memcpy(pbSignature.?[0..cbSignature], &rgbLmsLmsSHA256M24H5Signature);

    SymCryptInjectError(pbSignature.?, cbSignature);

    scError = SymCryptLmsVerifyInternal(
        pKey.?,
        &selftest.SymCryptTestMsg3,
        selftest.SymCryptTestMsg3.len,
        0,
        pbSignature.?,
        cbSignature,
    );
    SYMCRYPT_FIPS_ASSERT(scError == .SYMCRYPT_NO_ERROR);

    SymCryptWipe(@ptrCast(pbSignature.?), cbSignature);
    SymCryptCallbackFree(@ptrCast(pbSignature.?));

    SymCryptLmskeyFree(pKey.?);
}

